#[test]
fn the_typed_default_differs_from_the_recorded_string_only_at_padding() {
    // The exact statement of the padding normalization (see the
    // `DEFY_DEFAULT_KEYMAP_DATA` docs): our serialized default differs
    // from the recorded data string ONLY at the ten wire-padding
    // positions the LAYOUT does not model, and only in `65535` → `0`.
    // Every modeled key of every layer is byte-identical.
    let recorded = recorded();
    let config = defy_default_config();

    // The modeled positions, read off the type itself: a cleared
    // layer's `to_keymap_data` answers `None` exactly there (the same
    // idiom the conversion layer uses to name its normalized
    // padding).
    let modeled: std::collections::HashSet<usize> =
        DefyKeymapLayer::new_cleared_to(KeyKind::from(0))
            .to_keymap_data()
            .iter()
            .enumerate()
            .filter(|(_, key)| key.is_some())
            .map(|(position, _)| position)
            .collect();

    let our_data = config.keymap.to_keymap_custom_data();
    let ours = tokens(&our_data);
    let recorded_tokens = tokens(&recorded.defy.wireless.keymap_custom);

    assert_eq!(ours.len(), recorded_tokens.len());

    for layer in 0..10 {
        for position in 0..80 {
            let index = layer * 80 + position;

            if modeled.contains(&position) {
                assert_eq!(
                    ours[index], recorded_tokens[index],
                    "layer {layer}, wire position {position} is a modeled \
                     key and must match the recorded default"
                );
            } else {
                assert_eq!(
                    ours[index], "0",
                    "layer {layer}, wire position {position} is a \
                     padding slot and must normalize to 0"
                );
                assert!(
                    recorded_tokens[index] == "0" || recorded_tokens[index] == "65535",
                    "layer {layer}, wire position {position}: unexpected \
                     recorded padding value"
                );
            }
        }
    }
}

#[test]
fn defy_default_superkeys_serialize_to_the_recorded_bazecor_data() {
    let recorded = recorded();
    let config = defy_default_config();

    let data = parsing::superkeys::SuperkeyMap::from(&config.superkeys)
        .to_command_data::<{ DefyKeyboard::SUPERKEY_MEMORY_SIZE }>()
        .expect("the default superkeys map fits the device memory");

    // The device write carries the live tokens first (the default
    // superkey, its terminator, and the map terminator), then the
    // `65535` padding to the 512-slot memory. The recorded virtual
    // data is the live bytes only, so the comparison is: the recorded
    // tokens are exactly the live prefix, and nothing else but the
    // padding follows.
    let all = tokens(&data);
    let live = tokens(&recorded.defy.wireless.superkeys_map);

    assert_eq!(all[..live.len()], live[..]);
    assert!(all[live.len()..].iter().all(|token| *token == "65535"));
}

