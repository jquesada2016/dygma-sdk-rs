//! Tests for the per-product default configs.
//!
//! The differential tests compare this module's output, at the data
//! level, against `tools/bazecor-differential/expectations/
//! default-configs.json` — the defaults recorded from Bazecor's own
//! hardware-virtual keyboards (and cross-checked at record time
//! against the shipped default backups). See the [module
//! docs](super) for the evidence map.

use super::*;
use crate::{
    devices::defy::{DefyColormap, DefyKeyboard, DefyKeymapLayer, MacroAction},
    devices::sonsei::{KEYS_PER_LAYER, SonseiColormap, SonseiKeymap, SonseiKeymapLayer},
    focus_api::parsing,
    focus_api::parsing::palette::{Palette, RgbPalette},
    keycode_tables::KeyKind,
};

/// The recorded defaults, typed down to the fields the comparisons
/// need; serde ignores the fields the comparisons don't need
/// (identity, settings, the recorded palettes and colormaps).
#[derive(serde::Deserialize)]
struct RecordedDefaults {
    /// The Bazecor commit the recording ran against.
    bazecor_commit: String,
    defy: RecordedPair,
    sonsei: RecordedPair,
}

/// One product's recorded pair (only the Defy carries a wired
/// variant; the Sonsei pair is wireless-only).
#[derive(serde::Deserialize)]
struct RecordedPair {
    wired: Option<RecordedVirtual>,
    wireless: RecordedVirtual,
}

/// One recorded virtual keyboard's default config data.
#[derive(serde::Deserialize)]
struct RecordedVirtual {
    keymap_custom: String,
    superkeys_map: String,
    macros_map: String,
    palette: String,
    colormap_map: String,
}

/// The recorded expectations (generated by
/// `tools/bazecor-differential/record-defaults.mjs`).
fn recorded() -> RecordedDefaults {
    serde_json::from_str(include_str!(
        "../../../../tools/bazecor-differential/expectations/default-configs.json"
    ))
    .expect("the recorded default-configs expectation file parses")
}

/// The tokens of a recorded data string.
fn tokens(data: &str) -> Vec<&str> {
    data.split_whitespace().collect()
}

